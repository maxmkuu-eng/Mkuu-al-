const fs = require('fs');
const path = require('path');
const file = path.join(process.cwd(), 'server', 'exaSearch.ts');
if (!fs.existsSync(file)) throw new Error('[EXA-SPORTS] server/exaSearch.ts not found');
let source = fs.readFileSync(file, 'utf8');
const replacement = "function isFinalResultQuery(q:string){return /\\b(matokeo|score|full time|ft|result|nani ameshinda|nani kashinda|amecheza|alicheza|ilicheza|imeshinda|kashinda|ushindi|zimeishaje|imeishaje|yameishaje|zimekwisha|zimeisha|won|lost|draw|final)\\b/i.test(q)&&!/\\b(anacheza|tutacheza|will play|will face|ratiba|fixture|upcoming|kesho|leo|today)\\b/i.test(q);}";
const pattern = /function isFinalResultQuery\(q:string\)\{[^\n]*\}/;
if (!pattern.test(source)) throw new Error('[EXA-SPORTS] Final-result intent function not found.');
source = source.replace(pattern, replacement);
fs.writeFileSync(file, source, 'utf8');
console.log('[EXA-SPORTS] Relative-date match-result questions now route to final-result extraction.');
